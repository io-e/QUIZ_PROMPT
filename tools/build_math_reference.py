"""Build subjects/mathematics/reference/* FROM the v11 CSVs (read-only) and the PR #2 audit snapshot.
Every historical skill ID and error ID is preserved. Deterministic output."""
import csv, json, os, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V11 = os.path.join(R, "Math_Diagnostic_Reference_CLAUDE_v11")
OUT = os.path.join(R, "subjects", "mathematics", "reference")
sys.path.insert(0, R)
from quiz_eval.programme_diff import LINK_FIELDS, write_csv
AUD = os.path.join(OUT, "sources", "Official_Programme_Audit_600_GROK.csv")
PR2 = open(os.path.join(OUT, "sources", "PR2_COMMIT.txt")).read().strip()
EDITION = {"BAC_1RE_SPE": "MATH_1RE_SPE_2026", "BAC_1RE_COMMUN": "MATH_1RE_ES_2026", "BAC_TLE_SPE": "MATH_TLE_SPE_2019",
           "BAC_TLE_COMPLEMENTAIRES": "MATH_TLE_COMP_2019", "BAC_TLE_EXPERTES": "MATH_TLE_EXP_2019", "MP2I": "MATH_MP2I_2021", "MPI": "MATH_MPI_2021"}
STATUS = {"SUPPORTED": "PROPOSED", "PARTIALLY_SUPPORTED": "PROPOSED_PARTIAL", "NOT_SUPPORTED": "EXCLUDED_NOT_SUPPORTED", "UNVERIFIED": "QUARANTINE"}
T = list(csv.DictReader(open(os.path.join(V11, "Math_Diagnostic_Targets_v11.csv"), encoding="utf-8")))
A = {r["target_id"]: r for r in csv.DictReader(open(AUD, encoding="utf-8"))}
skills = []
for t in T:
    errs = json.loads(t["errors_json"])
    skills.append(dict(skill_id=t["id"], level=t["level"], subdomain=t["subdomain"], capability=t["capability"], official_ref=t["official_ref"],
                       v11_anchor_status=t["anchor_status"], v11_status=t["status"], reference_version="MATH_REF_v11",
                       error_ids=" ".join(e["id"] for e in errs), error_statuses=" ".join(f"{e['id']}:{e['status']}" for e in errs)))
write_csv(os.path.join(OUT, "skills.csv"), skills, list(skills[0]))
links = []
def L(t, ed, status, conf, url, page, passage, note):
    links.append(dict(link_id=f"{t['id']}@{ed}", skill_id=t["id"], edition_id=ed, official_ref=t["official_ref"], link_status=status,
                      verification=conf, source_url=url, page=page, verbatim_passage=passage,
                      evidence_origin=f"anchor_review audit, PR #2 @ {PR2[:12]} (proposal, not approved)", approval="PENDING", proposed_action=("TO_DECIDE: REANCHOR / PREREQUISITE / ENRICHMENT / RETIRED_FROM_EXAM_SELECTION" if status=="QUARANTINE" else ""), reviewer="", approved_on="", note=note))
for t in T:
    a = A[t["id"]]
    if t["level"] == "BREVET":
        f = a["edition_flag"]
        e20 = (a["source_url_2020"], a["page_2020"], a["passage_2020"]); e26 = (a["source_url_2026"], a["page_2026"], a["passage_2026"])
        if f == "BOTH":
            L(t, "MATH_C4_2020", "PROPOSED", a["conformity_2020"], *e20, "edition_flag=BOTH")
            L(t, "MATH_C4_2026", "PROPOSED", a["conformity_2026"], *e26, "edition_flag=BOTH")
        elif f == "2026_ONLY":
            L(t, "MATH_C4_2026", "PROPOSED", a["conformity_2026"], *e26, "edition_flag=2026_ONLY: no link to MATH_C4_2020, so excluded from DNB 2025-2028")
        elif f == "2020_ONLY":
            L(t, "MATH_C4_2020", "PROPOSED", a["conformity_2020"], *e20, "edition_flag=2020_ONLY: preserved for historical sessions; no 2026 link")
        else:
            L(t, "MATH_C4_2020", "QUARANTINE", a["conformity_2020"], *e20, "edition_flag=NEITHER: investigate first")
            L(t, "MATH_C4_2026", "QUARANTINE", a["conformity_2026"], *e26, "edition_flag=NEITHER: investigate first")
    else:
        L(t, EDITION[t["level"]], STATUS[a["conformity"]], a["conformity"], a["source_url"], a["page"], a["verbatim_passage"], f"audit conformity={a['conformity']}")
write_csv(os.path.join(OUT, "skill_programme_links.csv"), links)
af = ["target_id", "level", "current_official_ref", "conformity", "source_url", "page", "page_or_section", "verbatim_passage", "confidence", "consulted_on", "edition_flag"]
write_csv(os.path.join(OUT, "anchors.csv"), [A[t["id"]] for t in T], af)
pri = {"QUARANTINE": 0, "PROPOSED_PARTIAL": 2, "EXCLUDED_NOT_SUPPORTED": 3, "PROPOSED": 4}
wl = sorted(links, key=lambda l: (0 if "NEITHER" in l["note"] else 1 if l["skill_id"].startswith("BR-") else 2, pri.get(l["link_status"], 9), l["skill_id"], l["edition_id"]))
write_csv(os.path.join(R, "docs", "REVIEW_WORKLIST.csv"), [dict(priority=i + 1, **l) for i, l in enumerate(wl)], ["priority"] + LINK_FIELDS)
print(len(skills), "skills;", len(links), "links;", sum(1 for l in links if l["link_status"] == "QUARANTINE"), "quarantine links")

# REFERENCE.md is generated, never edited by hand
from collections import Counter
c = Counter((l["edition_id"], l["link_status"]) for l in links)
md = ["# Mathematics reference (generated by tools/build_math_reference.py – do not edit)", "",
      "Reference version **MATH_REF_v11** (source: `Math_Diagnostic_Reference_CLAUDE_v11/`, read-only). Curriculum alignment from the anchor_review audit of draft PR #2 (commit %s), **proposals only**: every link has approval=PENDING; no link is APPROVED, so no validated test can be generated yet. Release: paper HOLD, digital HOLD." % PR2[:12], "",
      f"- skills.csv: {len(skills)} skills (all v11 IDs), {sum(len(s['error_ids'].split()) for s in skills)} error IDs preserved",
      f"- skill_programme_links.csv: {len(links)} skill-to-edition links (many-to-many)", "- anchors.csv: the audit evidence per skill", "", "| edition | link_status | links |", "|---|---|---|"]
md += [f"| {e} | {s} | {n} |" for (e, s), n in sorted(c.items())]
md += ["", "Link statuses: PROPOSED (audit SUPPORTED), PROPOSED_PARTIAL, QUARANTINE (never selectable), EXCLUDED_NOT_SUPPORTED, TO_REVIEW (created by programme_diff for a new edition), APPROVED (teacher only)."]
open(os.path.join(OUT, "REFERENCE.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
